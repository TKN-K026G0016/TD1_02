#include "timer.h"

Timer::Timer(int time)
	:time_{ time } {
}

// ------------------------------------------------------------------------
// 【関数】Timer::Reset()
// 何をする？ この関数が担当する処理を以下の順番で実行する。
// 読み方：引数を確認 → ifで早期終了する条件 → 最後に更新/戻り値を確認。
// ------------------------------------------------------------------------
void Timer::Reset(void) {
	count_ = 0;
}

// ------------------------------------------------------------------------
// 【関数】Timer::CountUp()
// 何をする？ この関数が担当する処理を以下の順番で実行する。
// 読み方：引数を確認 → ifで早期終了する条件 → 最後に更新/戻り値を確認。
// ------------------------------------------------------------------------
void Timer::CountUp(void) {
	if (count_ >= time_) return;

	count_++;
}

// ------------------------------------------------------------------------
// 【関数】Timer::IsReady()
// 何をする？ 現在の状態や計算結果を返すための問い合わせ関数。
// 読み方：引数を確認 → ifで早期終了する条件 → 最後に更新/戻り値を確認。
// ------------------------------------------------------------------------
bool Timer::IsReady(void) const {
	return (count_ >= time_);
}